#!/usr/bin/env python3
# Launch-test harness for the ROS2Plan plan dispatch (ROS2 port of plan_dispatch.test).
# Brings up the full interfaced planning pipeline (knowledge base, problem interface, planner
# interface, plan parser and plan dispatcher) plus the simulated action nodes, then runs the gtest
# executable that drives problem_generation -> planning -> parse -> dispatch and inspects the
# action_dispatch / action_feedback / plan_graph topics.

import os
import unittest

from ament_index_python.packages import get_package_share_directory

import launch
import launch_ros.actions
import launch_testing
import launch_testing.actions
import launch_testing.asserts
import launch_testing.markers
from launch.actions import DeclareLaunchArgument, ExecuteProcess, TimerAction
from launch.substitutions import LaunchConfiguration

import pytest


def simulated_action(name, duration):
    # Each simulated action subscribes to the dispatcher's action_dispatch topic and publishes on
    # its action_feedback topic. Both nodes use the default (root) namespace, so the relative topic
    # names the dispatcher registers resolve to /action_dispatch and /action_feedback.
    return launch_ros.actions.Node(
        package='ros2plan_planning_system',
        executable='simulatedAction',
        name='ros2plan_interface_' + name,
        output='screen',
        parameters=[{
            'knowledge_base': 'ros2plan_knowledge_base',
            'pddl_action_name': name,
            'action_duration': duration,
            'action_dispatch_topic': 'action_dispatch',
            'action_feedback_topic': 'action_feedback',
        }],
    )


@pytest.mark.launch_test
@launch_testing.markers.keep_alive
def generate_test_description():
    pkg = get_package_share_directory('ros2plan_planning_system')
    common = os.path.join(pkg, 'test', 'pddl', 'turtlebot')
    domain_path = os.path.join(common, 'domain.pddl')
    # Initial state is loaded from this pddl; problem.pddl is auto-generated by the problem interface.
    initial_state_problem_path = os.path.join(common, 'initial_state_problem.pddl')
    autom_gen_problem_path = os.path.join(common, 'problem.pddl')
    data_path = common + os.sep
    planner_command = 'timeout 10 ' + os.path.join(pkg, 'common', 'bin', 'popf') + ' DOMAIN PROBLEM'

    knowledge_base = launch_ros.actions.Node(
        package='ros2plan_knowledge_base',
        executable='knowledgeBase',
        name='ros2plan_knowledge_base',
        output='screen',
        parameters=[{
            'domain_path': domain_path,
            'problem_path': initial_state_problem_path,
            'use_unknowns': False,
        }],
    )

    problem_interface = launch_ros.actions.Node(
        package='ros2plan_planning_system',
        executable='problemInterface',
        name='ros2plan_problem_interface',
        output='screen',
        parameters=[{
            'knowledge_base': 'ros2plan_knowledge_base',
            'domain_path': domain_path,
            'problem_path': autom_gen_problem_path,
            'problem_topic': 'problem_instance',
            'planning_language': 'PDDL',
        }],
    )

    planner_interface = launch_ros.actions.Node(
        package='ros2plan_planning_system',
        executable='popf_planner_interface',
        name='ros2plan_planner_interface',
        output='screen',
        parameters=[{
            'use_problem_topic': True,
            # All nodes run in the default namespace, so relative topic names resolve to the root
            # namespace and wire together (this mirrors the working run_demo.sh). The problem
            # interface publishes the problem on /problem_instance, so the planner must subscribe there.
            'problem_topic': 'problem_instance',
            'planner_topic': 'planner_output',
            'domain_path': domain_path,
            'problem_path': autom_gen_problem_path,
            'data_path': data_path,
            'planner_command': planner_command,
        }],
    )

    parsing_interface = launch_ros.actions.Node(
        package='ros2plan_planning_system',
        executable='pddl_esterel_plan_parser',
        name='ros2plan_parsing_interface',
        output='screen',
        parameters=[{
            'knowledge_base': 'ros2plan_knowledge_base',
            # Subscribe to the planner's output on the root /planner_output topic (the planner
            # publishes there), and publish the parsed plan on /complete_plan so the dispatcher,
            # which subscribes to the same relative name, receives it.
            'planner_topic': 'planner_output',
            'plan_topic': 'complete_plan',
        }],
    )

    plan_dispatcher = launch_ros.actions.Node(
        package='ros2plan_planning_system',
        executable='pddl_esterel_plan_dispatcher',
        name='ros2plan_plan_dispatcher',
        output='screen',
        parameters=[{
            'knowledge_base': 'ros2plan_knowledge_base',
            'plan_topic': 'complete_plan',
            'action_dispatch_topic': 'action_dispatch',
            'action_feedback_topic': 'action_feedback',
            'plan_graph_topic': 'plan_graph',
            'display_edge_type': False,
            'timeout_actions': False,
            'action_timeout_fraction': 0.0,
        }],
    )

    gtest = ExecuteProcess(
        cmd=[LaunchConfiguration('test_exe')],
        name='plan_dispatch_gtest',
        output='screen',
    )

    return launch.LaunchDescription([
        DeclareLaunchArgument('test_exe', description='Path to the gtest executable'),
        knowledge_base,
        problem_interface,
        planner_interface,
        parsing_interface,
        plan_dispatcher,
        # Simulated actions for the turtlebot domain (mirrors plan_dispatch.test).
        # Short durations keep the (blocking) dispatch of the whole plan well within the test's
        # service-call timeout.
        simulated_action('undock', 0.3),
        simulated_action('dock', 0.3),
        simulated_action('localise', 0.3),
        simulated_action('goto_waypoint', 0.3),
        # Give the nodes a moment to come up and the KB to parse the domain.
        # Wait long enough for the knowledge base to parse the domain AND for all four action
        # interfaces to finish their setup() KB queries before the gtest starts driving the
        # pipeline. The knowledge base serialises service calls, so if an action's setup query is
        # still pending when the dispatch starts hammering the KB it can queue for a long time.
        TimerAction(period=12.0, actions=[gtest]),
        launch_testing.actions.ReadyToTest(),
    ]), {'gtest': gtest}


class TestPlanDispatch(unittest.TestCase):

    def test_gtest_runs_to_completion(self, proc_info, gtest):
        # Wait for the gtest process to finish (it has its own internal timeouts).
        proc_info.assertWaitForShutdown(process=gtest, timeout=170)


@launch_testing.post_shutdown_test()
class TestPlanDispatchExitCode(unittest.TestCase):

    def test_gtest_exit_code(self, proc_info, gtest):
        # gtest returns 0 only if all assertions passed.
        launch_testing.asserts.assertExitCodes(proc_info, process=gtest)
